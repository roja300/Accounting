[CmdletBinding()]
param(
    [string]$EnvironmentFile = (Join-Path $PSScriptRoot "src/.env.production"),
    [switch]$ValidateOnly,
    [switch]$NoBrowser
)

$ErrorActionPreference = "Stop"

function Read-Setting {
    param(
        [string]$Prompt,
        [string]$DefaultValue,
        [string]$Pattern,
        [string]$ValidationMessage
    )

    while ($true) {
        $value = Read-Host "$Prompt [$DefaultValue]"
        if ([string]::IsNullOrWhiteSpace($value)) {
            $value = $DefaultValue
        }

        if ($value -match $Pattern) {
            return $value
        }

        Write-Warning $ValidationMessage
    }
}

function ConvertTo-PlainText {
    param([Security.SecureString]$SecureValue)

    $pointer = [IntPtr]::Zero
    try {
        $pointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($SecureValue)
        return [Runtime.InteropServices.Marshal]::PtrToStringBSTR($pointer)
    } finally {
        if ($pointer -ne [IntPtr]::Zero) {
            [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($pointer)
        }
    }
}

function Read-DatabasePassword {
    while ($true) {
        Write-Host "Use at least 16 characters containing only letters, numbers, periods, underscores, tildes, or hyphens."
        $password = ConvertTo-PlainText (Read-Host "PostgreSQL password" -AsSecureString)
        $confirmation = ConvertTo-PlainText (Read-Host "Confirm PostgreSQL password" -AsSecureString)

        if ($password -cne $confirmation) {
            Write-Warning "The passwords do not match. Try again."
            continue
        }

        if ($password -notmatch '^[A-Za-z0-9._~-]{16,}$') {
            Write-Warning "The password must be at least 16 characters and use only the supported characters."
            continue
        }

        return $password
    }
}

function New-ProductionEnvironmentFile {
    param([string]$Path)

    Write-Host "No production environment file was found. Let's create one."
    $user = Read-Setting "PostgreSQL user" "accounting" '^[A-Za-z0-9_]+$' "Use only letters, numbers, and underscores."
    $password = Read-DatabasePassword

    $content = @(
        "# Generated by start-production.ps1. This file is ignored by Git.",
        "POSTGRES_DB=accounting",
        "POSTGRES_USER=$user",
        "POSTGRES_PASSWORD=$password",
        "FRONTEND_PORT=3000",
        ""
    ) -join [Environment]::NewLine

    $encoding = New-Object System.Text.UTF8Encoding -ArgumentList $false
    [IO.File]::WriteAllText($Path, $content, $encoding)
    Write-Host "Created production configuration at $Path"
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw "Docker is required. Install or start Docker Desktop, then try again."
}

$environmentFilePath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($EnvironmentFile)
if (-not (Test-Path -LiteralPath $environmentFilePath -PathType Leaf)) {
    New-ProductionEnvironmentFile $environmentFilePath
}

$composeFile = Join-Path $PSScriptRoot "src/compose.production.yaml"
$composeArguments = @(
    "compose",
    "--env-file", $environmentFilePath,
    "--file", $composeFile
)

if ($ValidateOnly) {
    $dockerArguments = $composeArguments + @("config", "--quiet")
} else {
    $dockerArguments = $composeArguments + @("up", "--build", "--detach", "--wait")
}

& docker $dockerArguments
if ($LASTEXITCODE -ne 0) {
    throw "Docker Compose exited with code $LASTEXITCODE."
}

if (-not $ValidateOnly) {
    $publishedEndpoints = @(& docker @composeArguments port frontend 80)
    if ($LASTEXITCODE -ne 0 -or $publishedEndpoints.Count -eq 0) {
        throw "Accounting is running, but the published frontend port could not be determined."
    }

    $publishedEndpoint = $publishedEndpoints[0].Trim()
    if ($publishedEndpoint -notmatch ':(\d+)$') {
        throw "Accounting is running, but the published frontend port could not be determined."
    }

    $applicationUrl = "http://localhost:$($Matches[1])/"
    Write-Host "Accounting production containers are running at $applicationUrl"

    if (-not $NoBrowser) {
        try {
            Start-Process $applicationUrl
        } catch {
            Write-Warning "Accounting is running, but the browser could not be opened automatically. Open $applicationUrl manually."
        }
    }
}
